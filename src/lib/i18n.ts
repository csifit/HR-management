export type Dictionary = { [K in keyof typeof dictionaries.ro]: string };
export function dictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}
export function roleLabel(role: string, d: Dictionary) {
  return role === "employee"
    ? d.employeeRole
    : role === "manager"
      ? d.managerRole
      : role === "organisation_owner"
        ? d.organisation_owner
        : d.hr_manager;
}
export function dateLabel(date: string | null, locale: Locale) {
  return date
    ? new Intl.DateTimeFormat(locale === "ro" ? "ro-RO" : "en-GB", {
        day: "2-digit",
        month: "short",
        year: "numeric",
        timeZone: "Europe/Bucharest",
      }).format(new Date(date.length === 10 ? `${date}T12:00:00Z` : date))
    : "—";
}
export function moneyLabel(value: number, locale: Locale) {
  return new Intl.NumberFormat(locale === "ro" ? "ro-RO" : "en-GB", {
    style: "currency",
    currency: "RON",
    maximumFractionDigits: 2,
  }).format(value);
}
export function actionLabel(action: string, locale: Locale) {
  const labels: Record<string, [string, string]> = {
    "employee.created": ["Angajat adăugat", "Employee added"],
    "employee.updated": ["Profil actualizat", "Profile updated"],
    "contract.created": ["Contract adăugat", "Contract added"],
    "contract.updated": ["Contract actualizat", "Contract updated"],
    "salary.changed": ["Salariu actualizat", "Salary updated"],
    "organisation.created": ["Organizație creată", "Organisation created"],
    "organisation.updated": ["Organizație actualizată", "Organisation updated"],
    "membership.updated": ["Acces actualizat", "Access updated"],
  };
  return labels[action]?.[locale === "ro" ? 0 : 1] ?? action;
}
